// Fallback pool in case of an unknown slug
export const defaultQuizPool: QuizQuestion[] = domainQuizBank['fullstack-developer'];

// Helper to shuffle array (Fisher-Yates) and return 'count' random questions for a specific domain
export function getRandomDomainQuestions(domainSlug: string, count = 5): QuizQuestion[] {
  const pool = domainQuizBank[domainSlug] || defaultQuizPool;
  // Duplicate pool array so we don't mutate original
  const shuffled = [...pool];
  
  // Fisher-Yates shuffle
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  
  return shuffled.slice(0, count);
}

