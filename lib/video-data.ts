export function getVideosByCategory(category: string): LearningVideo[] {
  if (category === 'All') return learningVideos;
  return learningVideos.filter((v) => v.category === category);
}

export function getReelsByTopic(topic: string): LearningReel[] {
  if (topic === 'All') return learningReels;
  return learningReels.filter((r) => r.topic === topic);
}

export function getRecommendedVideos(careerCategory: string): LearningVideo[] {
  const categoryMap: Record<string, string[]> = {
    'Data Science': ['AI & Machine Learning', 'Python'],
    'Web Development': ['Career Guidance', 'Java'],
    'Cyber Security': ['Cyber Security'],
    'Cloud & DevOps': ['Cloud Computing'],
    'Software Engineering': ['Java', 'C++', 'Data Structures'],
    'AI Engineer': ['AI & Machine Learning', 'Python'],
  };

  const relevantCategories = categoryMap[careerCategory] || ['Python', 'AI & Machine Learning'];
  return learningVideos.filter((v) => relevantCategories.includes(v.category)).slice(0, 4);
}
